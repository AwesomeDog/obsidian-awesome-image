// Fills <vault>/Awesome Image Dev with notes and images so Awesome Image has
// something to work on. Images are downloaded from Wikimedia Commons when
// seeding runs, so the repository itself never carries binaries.
//
// Usage: npm run seed -- <vault-path>
//
// The vault path defaults to $OBSIDIAN_VAULT. The fixture folder is always
// overwritten; nothing outside it is touched.

import {mkdir, readdir, rm, stat, writeFile} from "node:fs/promises";
import path from "node:path";

const FIXTURE_FOLDER = "Awesome Image Dev";
const MARKER = ".awesome-image-seed.json";
const USER_AGENT = "obsidian-awesome-image-seed/1.0 (dev fixture script)";
const DOWNLOAD_TIMEOUT_MS = 20_000;
const DOWNLOAD_ATTEMPTS = 4;

