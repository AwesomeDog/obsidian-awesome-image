async function write(relativePath, content, encoding) {
  const file = path.join(target, relativePath);
  await mkdir(path.dirname(file), {recursive: true});
  await writeFile(file, content, encoding);
}

for (const [relativePath, content] of Object.entries(NOTES)) {
  await write(relativePath, content, "utf8");
}

// One request per distinct URL, sequentially: Wikimedia rate limits bursts.
const cache = new Map();

async function fetchBytes(url) {
  const cached = cache.get(url);
  if (cached) return cached;

  let lastError;
  for (let attempt = 1; attempt <= DOWNLOAD_ATTEMPTS; attempt += 1) {
    try {
      const response = await fetch(url, {
        headers: {"User-Agent": USER_AGENT},
        signal: AbortSignal.timeout(DOWNLOAD_TIMEOUT_MS),
      });
      if (!response.ok) throw new Error(`${response.status} ${response.statusText}`);
      const bytes = Buffer.from(await response.arrayBuffer());
      cache.set(url, bytes);
      return bytes;
    } catch (error) {
      lastError = error;
      // Wikimedia throttles bursts, so back off generously between attempts.
      if (attempt < DOWNLOAD_ATTEMPTS) {
        await new Promise((resolve) => setTimeout(resolve, attempt * 3000));
      }
    }
  }
  throw lastError;
}

let failed = 0;
for (const image of IMAGES) {
  try {
    await write(image.file, await fetchBytes(image.url));
  } catch (error) {
    failed += 1;
    console.warn(`  ! ${image.file}: ${error.message}`);
  }
}

await write(
  MARKER,
  `${JSON.stringify(
    {
      generator: "obsidian-awesome-image/scripts/seed.mjs",
      createdAt: new Date().toISOString(),
      folder: FIXTURE_FOLDER,
    },
    null,
    2
  )}\n`,
  "utf8"
);

const written = Object.keys(NOTES).length + IMAGES.length - failed + 1;
console.log(`Seeded ${written} files in ${target}`);
console.log(`Images: ${IMAGES.length - failed} downloaded, ${failed} failed.`);
if (failed) process.exitCode = 1;
