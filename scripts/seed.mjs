const vaultArgument = process.argv[2] || process.env.OBSIDIAN_VAULT;

if (!vaultArgument) {
  console.error("Usage: npm run seed -- <vault-path>");
  process.exit(1);
}

const vault = path.resolve(vaultArgument);
const target = path.join(vault, FIXTURE_FOLDER);

const vaultStats = await stat(vault).catch(() => null);
if (!vaultStats?.isDirectory()) {
  console.error(`Not a directory: ${vault}`);
  process.exit(1);
}

if (!(await stat(path.join(vault, ".obsidian")).catch(() => null))) {
  console.warn(`Warning: no .obsidian folder in ${vault} - is this a vault root?`);
}

const existing = await readdir(target).catch(() => []);
if (existing.length) {
  // Only ever wipe a folder this script built, never a real notes folder that
  // happens to share the name.
  if (!existing.includes(MARKER)) {
    console.error(
      `${target} is not an Awesome Image fixture folder. Move it away or delete it by hand first.`
    );
    process.exit(1);
  }
  await rm(target, {recursive: true, force: true});
}

